/**
 * Post-hoc diagnostics for the article, from saved records only (no credentials, no model process).
 *
 *   npm run diagnose -- --label cohort-03
 *
 * Writes results/<label>-rejections.csv, results/<label>-diagnostics.md and
 * results/<label>-walkthrough.json. Reads attempt.json, stage.json, verdict.json and checks/*.json;
 * accounting is regenerated in memory exactly as `npm run analyse` does. Writes nothing under records/.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { BENCHMARK_ROOT } from '../src/fixtures.ts';
import { loadAnalysisConfig, readCampaign } from '../src/analysis/load.ts';
import type { AttemptAccounting } from '../src/accounting/record.ts';
import { CLASSES, checkRunTable, rejectionTable, selectTraceKey, type DiagnosticRow } from './diagnostics.ts';

const { values } = parseArgs({ options: { label: { type: 'string' }, 'results-dir': { type: 'string' } } });
const label = values.label;
if (!label || !/^[a-z0-9][a-z0-9-]*$/.test(label)) {
  console.error('usage: npm run diagnose -- --label <campaign-label> [--results-dir DIR]');
  process.exit(2);
}
const cfg = loadAnalysisConfig(BENCHMARK_ROOT);
const records = readCampaign(BENCHMARK_ROOT, label);
if (records.length === 0) {
  console.error(`no attempt records under records/${label}`);
  process.exit(1);
}
const pad = (n: number) => String(n).padStart(2, '0');
const attemptDir = (a: AttemptAccounting) => join(BENCHMARK_ROOT, 'records', label, `block-${pad(a.block)}`, `slot-${pad(a.slot)}-${a.conditionId}`, `attempt-${a.attempt}`);
const readJson = (p: string): any => JSON.parse(readFileSync(p, 'utf8'));

const rows: Array<DiagnosticRow & { acc: AttemptAccounting; dir: string }> = records.map((acc) => {
  const dir = attemptDir(acc);
  const verdict = existsSync(join(dir, 'verdict.json')) ? readJson(join(dir, 'verdict.json')) : null;
  const checksDir = join(dir, 'checks');
  const checkRuns = existsSync(checksDir)
    ? readdirSync(checksDir).filter((f) => /^\d+\.json$/.test(f)).sort().map((f) => {
        const c = readJson(join(checksDir, f));
        return { status: String(c.status), failedSuites: (c.suites ?? []).filter((s: any) => s.status === 'failed').map((s: any) => String(s.suite)) };
      })
    : [];
  return {
    acc,
    dir,
    conditionId: acc.conditionId,
    block: acc.block,
    slot: acc.slot,
    scored: acc.scored,
    accepted: acc.accepted,
    buildOk: verdict?.build && typeof verdict.build.ok === 'boolean' ? verdict.build.ok : null,
    cases: (verdict?.cases ?? []).map((c: any) => ({ id: String(c.id), passed: c.passed === true, detail: String(c.detail ?? '') })),
    checkRuns,
  };
});

const usd = (pico: bigint) => `$${(Number(pico) / 1e12).toFixed(4)}`;
const tokens = (t: AttemptAccounting['totals']['tokens']) => Object.fromEntries(Object.entries(t).map(([k, q]) => [k, q.hi === null ? (q.lo === 0 ? 'unknown' : `>= ${q.lo}`) : q.lo === q.hi ? q.lo : `${q.lo}-${q.hi}`]));

// Rejection classes per condition.
const table = rejectionTable(rows);
const csv = [['condition', 'scored', ...CLASSES].join(','), ...table.map((c) => [c.conditionId, c.scored, ...CLASSES.map((k) => c[k])].join(','))].join('\n') + '\n';

// Totals by check condition and by workflow.
const sumBy = (key: (c: string) => string) => {
  const m = new Map<string, Record<string, number>>();
  for (const c of table) {
    const k = key(c.conditionId);
    const t = m.get(k) ?? { scored: 0, ...Object.fromEntries(CLASSES.map((x) => [x, 0])) };
    t.scored! += c.scored;
    for (const x of CLASSES) t[x]! += c[x];
    m.set(k, t);
  }
  return [...m.entries()].sort(([a], [b]) => (a < b ? -1 : 1));
};
const checks = checkRunTable(rows);

// Failed evaluator cases among rejected workflows.
const caseFails = new Map<string, number>();
for (const r of rows) if (r.scored && r.accepted !== true) for (const c of r.cases) if (!c.passed) caseFails.set(c.id, (caseFails.get(c.id) ?? 0) + 1);

// Walkthrough trace, by the declared rule.
const key = selectTraceKey(rows);
const trace = key ? rows.find((r) => r.scored && r.block === key.block && r.slot === key.slot)! : null;
let walkthrough: unknown = null;
const md: string[] = [];
md.push(`# Post-hoc diagnostics: ${label}`, '');
md.push('Generated by `npm run diagnose` from saved records. These diagnostics explain rejections; they change no verdict, acceptance, denominator or cost. Dollars are API-equivalent estimates from the ' + cfg.snapshotDate + ' cost.dev snapshot, not subscription charges.', '');
md.push('## Rejection classes', '', 'Each scored workflow is in exactly one class, tested in this order: accepted; the evaluator could not build the snapshot; it built but never answered `/health` within 10 s; the only failed case was the attempt-count assertion in `A7.inflight-resumed`; anything else.', '');
md.push(`| Group | Scored | ${CLASSES.join(' | ')} |`, `| --- | --- | ${CLASSES.map(() => '---').join(' | ')} |`);
for (const [k, t] of sumBy((c) => `checks ${c.split('.').pop()}`)) md.push(`| ${k} | ${t.scored} | ${CLASSES.map((x) => t[x]).join(' | ')} |`);
for (const [k, t] of sumBy((c) => `workflow ${c.split('.')[0]}`)) md.push(`| ${k} | ${t.scored} | ${CLASSES.map((x) => t[x]).join(' | ')} |`);
const all = sumBy(() => 'all');
for (const [k, t] of all) md.push(`| ${k} | ${t.scored} | ${CLASSES.map((x) => t[x]).join(' | ')} |`);
md.push('', `Per condition: \`${label}-rejections.csv\`.`, '');
md.push('## Deterministic check runs (checks-on workflows)', '');
md.push(`- Workflows with check runs: ${checks.workflowsWithChecks}; runs: ${checks.runs} (${checks.passedRuns} passed, ${checks.failedRuns} failed).`);
md.push(`- Failed runs by suite: ${Object.entries(checks.failedBySuite).map(([s, n]) => `${s} ${n}`).join(', ') || 'none'}.`);
md.push(`- Last check run passed and independently accepted: ${checks.finalPassedAccepted}; last run passed but rejected: ${checks.finalPassedRejected}; last run failed: ${checks.finalFailed}.`, '');
md.push('## Failed evaluator cases among rejected workflows', '', '| Case | Rejected workflows failing it |', '| --- | --- |');
for (const [id, n] of [...caseFails.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))) md.push(`| ${id} | ${n} |`);
md.push('');

if (trace) {
  const a = trace.acc;
  const verdict = readJson(join(trace.dir, 'verdict.json'));
  const same = records.filter((r) => r.scored && r.conditionId === a.conditionId).sort((x, y) => x.block - y.block || x.slot - y.slot);
  const exactAll = same.every((r) => r.totals.cost.status === 'exact');
  const total = exactAll ? same.reduce((s, r) => s + BigInt(r.totals.cost.picoUsd!), 0n) : null;
  const accepted = same.filter((r) => r.accepted === true).length;
  walkthrough = {
    rule: 'first scored workflow in the seeded schedule (lowest block, then lowest slot)',
    record: `records/${label}/block-${pad(a.block)}/slot-${pad(a.slot)}-${a.conditionId}/attempt-${a.attempt}`,
    conditionId: a.conditionId,
    termination: a.termination,
    accepted: a.accepted,
    activeMs: a.activeMs,
    sensorRepairs: a.sensorRepairs,
    evaluation: { status: verdict.status, passedCases: verdict.passedCases, totalCases: verdict.totalCases, durationMs: verdict.durationMs },
    checkRuns: trace.checkRuns,
    stages: a.stages.map((s) => ({ id: s.id, kind: s.kind, role: s.role, requestedModel: s.requestedModel, resolvedModel: s.resolvedModel, durationMs: s.durationMs, termination: s.termination, tokens: tokens(s.tokens), cost: s.cost })),
    totals: { tokens: tokens(a.totals.tokens), cost: a.totals.cost },
    condition: {
      workflows: same.map((r) => ({ block: r.block, slot: r.slot, accepted: r.accepted, termination: r.termination, cost: r.totals.cost.status === 'exact' ? r.totals.cost.usd : null, costStatus: r.totals.cost.status })),
      accepted,
      scored: same.length,
      totalCostUsd: total === null ? null : Number(total) / 1e12,
      costPerAcceptedUsd: total === null || accepted === 0 ? null : Number(total) / 1e12 / accepted,
    },
  };
  md.push('## Walkthrough trace', '', `Rule: the first scored workflow in the seeded schedule. Selected: \`records/${label}/block-${pad(a.block)}/slot-${pad(a.slot)}-${a.conditionId}/attempt-${a.attempt}\` (${a.conditionId}), ${a.termination}, accepted=${a.accepted}, ${a.sensorRepairs} sensor repair(s), evaluator ${verdict.passedCases}/${verdict.totalCases} cases.`, '');
  md.push('| Stage | Role | Model | Minutes | Input | Cached input | Cache write 5m | Cache write 1h | Output | Cost |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const s of a.stages) {
    const t = tokens(s.tokens);
    md.push(`| ${s.id} | ${s.role} | ${s.resolvedModel} | ${((s.durationMs ?? 0) / 60000).toFixed(2)} | ${t.input_tokens} | ${t.cached_input_tokens} | ${t.cache_write_5m_tokens} | ${t.cache_write_1h_tokens} | ${t.output_tokens} | ${s.cost.status === 'exact' ? usd(BigInt(s.cost.picoUsd!)) : s.cost.status} |`);
  }
  md.push(`| total |  |  | ${((a.activeMs ?? 0) / 60000).toFixed(2)} active |  |  |  |  |  | ${a.totals.cost.status === 'exact' ? usd(BigInt(a.totals.cost.picoUsd!)) : a.totals.cost.status} |`, '');
  md.push(`Condition ${a.conditionId}: ${accepted} of ${same.length} accepted; total estimated cost ${total === null ? 'not exact' : usd(total)}; cost per accepted workflow ${total === null || accepted === 0 ? 'undefined' : usd(total / BigInt(accepted))} (rounded; exact value in the walkthrough JSON).`, '');
  md.push('| Block | Slot | Accepted | Termination | Cost |', '| --- | --- | --- | --- | --- |');
  for (const r of same) md.push(`| ${r.block} | ${r.slot} | ${r.accepted} | ${r.termination} | ${r.totals.cost.status === 'exact' ? usd(BigInt(r.totals.cost.picoUsd!)) : r.totals.cost.status} |`);
  md.push('');
}

const resultsDir = resolve(BENCHMARK_ROOT, values['results-dir'] ?? 'results');
mkdirSync(resultsDir, { recursive: true });
writeFileSync(join(resultsDir, `${label}-rejections.csv`), csv);
writeFileSync(join(resultsDir, `${label}-diagnostics.md`), md.join('\n'));
writeFileSync(join(resultsDir, `${label}-walkthrough.json`), `${JSON.stringify(walkthrough, null, 2)}\n`);
console.log(`results/${label}-rejections.csv\nresults/${label}-diagnostics.md\nresults/${label}-walkthrough.json`);
console.log(`classified ${rows.filter((r) => r.scored).length} scored workflow(s): ${CLASSES.map((c) => `${c} ${all[0]?.[1][c] ?? 0}`).join(', ')}`);

